"""Publication: the results hash, and the claim that a stranger can recompute it.

``bible/05`` §9b, and the property is not "we computed a hash". It is **"anyone
holding the export can recompute it"** -- which is what turns the threat model's
J-10 from *detected* into *detectable by a third party*, and the difference
between a claim and a control.

Every test here is arranged so it can fail. The centrepiece exports the database,
wipes it, imports it, and recomputes the digest from the restored rows: **the
escape hatch and the publication claim are the same property viewed from two
sides.**
"""

